/* The bento's Hand-off drawing: brand/illustration-trials/anatomy/handoff.mjs, re-stacked for the bento's
   tile (Rafael, 16 Oct: "make the format icon bigger and adjust the stack of the formats so it feels more
   portrait to better match the density of the others"). The files float in a stack, one above another, a little
   offset, instead of fanning flat across the page, so the drawing stands tall; coming apart, the stack opens
   upward. Bigger format icons and labels. The landing keeps the original.
   Writes brand/bento/art/handoff.ts:  node brand/bento/art/handoff.build.mjs */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { k, P, at, S, L, D, bright, apart, defs, WIDTH, HEIGHT } from "../../illustration-trials/anatomy/shared.mjs";

const DOC = { w: 62, d: 78 }, FOLD = 12, T = 1.6, LIFT = 4, NUDGE = [16, 24], SPREAD = 9, ICON = 1.7; // each file sits NUDGE in from the one below, along both edges (straight down the page in this view), so its top strip shows
const FILES = [
  { label: "PNG", icon: "picture" },
  { label: "SVG", icon: "curve" },
  { label: "MP4", icon: "play" },
  { label: "{ }", icon: null },
];
const origin = (i) => [-DOC.w / 2 - 24 + i * NUDGE[0], -DOC.d / 2 - 36 + i * NUDGE[1]];
const zOf = (i) => i * LIFT
const page = ([x, y]) => [[x, y], [x + DOC.w - FOLD, y], [x + DOC.w, y + FOLD], [x + DOC.w, y + DOC.d], [x, y + DOC.d]];

// the icons, drawn at ICON times the original's size about their left edge
function icon(kind, [x, y], z) {
  const s = ICON, X = (u) => x + u * s, Y = (v) => y + v * s
  if (kind === "picture") return L(k.planOutline({ x, y: Y(-4), w: 11 * s, d: 8 * s, r: 0 }, z, P), { tone: "mid" }) + L(k.onTop([[X(1.5), Y(2.5)], [X(4.5), Y(-0.5)], [X(6.5), Y(1.5)], [X(8), Y(0)], [X(9.5), Y(2.5)]], z, P), { tone: "mid", free: true });
  if (kind === "curve") return L(k.onTop(Array.from({ length: 9 }, (_, i) => { const t = i / 8; return [X(t * 11), Y(2.5 - Math.sin(t * Math.PI) * 6)]; }), z, P), { tone: "mid", free: true }) + D([at([X(0), Y(2.5), z]), at([X(11), Y(2.5), z])], { size: 1.2, tone: "mid" });
  if (kind === "play") return L(k.onTop([[X(2), Y(-4)], [X(10), Y(0)], [X(2), Y(4)]], z, P, true), { tone: "mid" });
  return "";
}
function doc(i) {
  const o = origin(i), z = zOf(i), top = z + T, f = FILES[i], last = i === FILES.length - 1;
  const ring = page(o), paths = k.extrude(ring, z, T, P, { bevel: 0.3 });
  const [x, y] = o, out = [last ? bright(paths, "achiote") : S(paths, { tone: "hi", crease: "lo" })];
  out.push(L(k.onTop([[x + DOC.w - FOLD, y], [x + DOC.w - FOLD, y + FOLD], [x + DOC.w, y + FOLD]], top, P), { tone: last ? "ink" : "lo" }));
  const sy = y + 12;
  out.push(icon(f.icon, [x + 6, sy], top));
  out.push(k.faceTextSvg(k.topMatrix([x + (f.icon ? 6 + 11 * ICON + 5 : 7), sy + 5], top, P, "x"), f.label, { size: last ? 18 : 14, tone: last ? "ink" : "hi" }));
  [[30, 34], [38, 22], [46, 28]].forEach(([dy, w]) => out.push(L(k.lineOnTop([x + 7, y + dy], [x + 7 + w, y + dy], top, P), { tone: last ? "ink-faint" : "faint", free: true })));
  return out.join("");
}

// frame it like the kit's other drawings: fit the stack (at rest and fanned) into the same box, centred
const pts = FILES.flatMap((_, i) => {
  const back = FILES.length - 1 - i, o = origin(i)
  return page(o).flatMap(([x, y]) => [0, 1].flatMap((a) => [at([x - a * SPREAD * 0.7 * back, y - a * SPREAD * back, zOf(i)]), at([x - a * SPREAD * 0.7 * back, y - a * SPREAD * back, zOf(i) + T])]))
})
const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1])
const [x0, y0, x1, y1] = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)]
const FIT = [440, 470], CENTRE = [300, 296]
const zoom = Math.min(FIT[0] / (x1 - x0), FIT[1] / (y1 - y0)), cx = (x0 + x1) / 2, cy = (y0 + y1) / 2
const transform = `translate(${CENTRE[0]} ${CENTRE[1]}) scale(${zoom.toFixed(3)}) translate(${(-cx).toFixed(1)} ${(-cy).toFixed(1)})`

// coming apart, the files below slide further back along the stack, so it fans open and every format shows
const art = FILES.map((_, i) => { const back = FILES.length - 1 - i; return back ? `<g ${apart([-SPREAD * 0.7 * back, -SPREAD * back, 0], back * 0.05)}>${doc(i)}</g>` : doc(i) })
console.log({ zoom: zoom.toFixed(2), box: [x0, y0, x1, y1].map((n) => Math.round(n)) })
const svg = `<svg xmlns="http://www.w3.org/2000/svg" class="iso-svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" aria-hidden="true">${defs("achiote")}<g transform="${transform}">${art.join("")}</g></svg>`
const out = join(dirname(fileURLToPath(import.meta.url)), "handoff.ts")
writeFileSync(out, `/* Generated by brand/bento/art/handoff.build.mjs: the kit's Hand-off drawing re-stacked portrait for the bento. Don't edit: change the build and run it again. */\nexport const HANDOFF_SVG = ${JSON.stringify(svg)}\n`)
console.log(`wrote ${out}`)
